#!/usr/bin/env python3
"""Generate docs/developers/api-endpoints.md from the bridge's own OpenAPI schema.

The table is built from ``create_app().openapi()``: the same schema the running bridge
serves at ``/openapi.json``. Nothing is started: no lifespan, no poller, no gateway I/O.
A throwaway DATA_DIR is used so the import cannot touch a real database.

Rerun after any change to the HTTP API:

    .venv/bin/python tools/gen_api_reference.py            # writes the page
    .venv/bin/python tools/gen_api_reference.py --check    # exit 1 if the page is stale
    .venv/bin/python tools/gen_api_reference.py --json out.json   # also dump the schema
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "developers" / "api-endpoints.md"
METHODS = ("get", "post", "put", "patch", "delete")


def _schema() -> dict:
    os.environ.setdefault("DATA_DIR", tempfile.mkdtemp(prefix="fwh-apiref-"))
    sys.path.insert(0, str(ROOT / "src"))
    from franklinwh_direct_connect_bridge import environment
    environment.DATA_DIR = os.environ["DATA_DIR"]
    from franklinwh_direct_connect_bridge.app import create_app
    return create_app().openapi()


def _group(path: str) -> str:
    parts = [p for p in path.split("/") if p]
    if not parts or parts[0] != "api":
        return "(UI and static)"
    return parts[1] if len(parts) > 1 else "api"


def _resolve(schema: dict, node: dict | None) -> dict:
    while node and "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        node = schema["components"]["schemas"].get(name, {})
    return node or {}


def _takes_confirm(schema: dict, op: dict) -> bool:
    if any(p.get("name") == "confirm" for p in op.get("parameters", [])):
        return True
    body = op.get("requestBody", {}).get("content", {}).get("application/json", {})
    model = _resolve(schema, body.get("schema"))
    return "confirm" in (model.get("properties") or {})


def _summary(op: dict) -> str:
    text = (op.get("description") or "").strip().split("\n\n")[0]
    text = " ".join(text.split())
    if not text:
        text = op.get("summary", "")
    if len(text) > 140:
        text = text[:137].rstrip() + "..."
    return text.replace("|", "\\|")


def render(schema: dict) -> str:
    groups: dict[str, list[tuple[str, str, str, bool]]] = defaultdict(list)
    for path, item in schema["paths"].items():
        for m in METHODS:
            if m in item:
                op = item[m]
                groups[_group(path)].append(
                    (m.upper(), path, _summary(op), _takes_confirm(schema, op)))
    total = sum(len(v) for v in groups.values())
    out = [
        "# REST endpoint reference",
        "",
        "[Developers Guide](index.md) · [REST API and OpenAPI](rest-api.md)",
        "",
        "!!! note \"Generated file\"",
        "    Generated by `tools/gen_api_reference.py` from the bridge's own OpenAPI schema",
        f"    (`create_app().openapi()`, bridge version {schema['info']['version']}). Do not edit",
        "    by hand: change the code, then rerun the script. The running bridge serves the",
        "    same schema at `/openapi.json`, which is the authority for request and response",
        "    bodies.",
        "",
        f"{total} operations on {len(schema['paths'])} paths, grouped by the path segment after",
        "`/api/`. **Description** is the first paragraph of the handler's docstring, cut at",
        "140 characters. **confirm** is ticked when the request takes a `confirm` field or",
        "query parameter; see [write safety](rest-api.md#write-safety) for what it does.",
        "",
    ]
    for g in sorted(groups):
        out += [f"## {g}", "", "| Method | Path | confirm | Description |",
                "|---|---|---|---|"]
        for meth, path, summ, conf in sorted(groups[g], key=lambda r: (r[1], r[0])):
            out.append(f"| {meth} | `{path}` | {'yes' if conf else ''} | {summ} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the page is stale")
    ap.add_argument("--json", help="also write the OpenAPI schema to this file")
    a = ap.parse_args()
    schema = _schema()
    page = render(schema)
    if a.json:
        Path(a.json).write_text(json.dumps(schema, indent=2))
    if a.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != page:
            print(f"{OUT.relative_to(ROOT)} is stale; rerun tools/gen_api_reference.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(page)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
